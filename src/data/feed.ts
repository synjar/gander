import type { FeedPost } from './types'
import { usersById } from './users'
import { img } from '../lib/img'

let n = 0

function post(
  userId: string,
  type: FeedPost['type'],
  businessId: string,
  businessName: string,
  neighbourhood: string,
  text: string,
  time: string,
  opts: Partial<FeedPost> = {},
): FeedPost {
  const u = usersById[userId]
  n += 1
  return {
    id: `feed-${n}`,
    userId,
    userName: u.name,
    userAvatar: u.avatar,
    userLevel: u.level,
    type,
    businessId,
    businessName,
    neighbourhood,
    text,
    photos: [],
    likes: 0,
    comments: 0,
    time,
    ...opts,
  }
}

