const DAYS = [
  'Monday',
  'Tuesday',
  'Wednesday',
  'Thursday',
  'Friday',
  'Saturday',
  'Sunday',
]

function makeHours(
  open: string,
  close: string,
  weekend?: { open: string; close: string },
  closed: string[] = [],
): OpeningHours[] {
  return DAYS.map((day) => {
    if (closed.includes(day)) return { day, open: 'Closed', close: '' }
    const isWeekend = day === 'Saturday' || day === 'Sunday'
    if (isWeekend && weekend) return { day, open: weekend.open, close: weekend.close }
    return { day, open, close }
  })
}

function gallery(keywords: string, base: number, extra?: string): string[] {
  return [
    img(keywords, base + 1),
    img(keywords, base + 2),
    img(keywords, base + 3),
    img(extra ?? keywords, base + 4),
  ]
}

